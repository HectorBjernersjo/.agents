#!/usr/bin/env bash

set -euo pipefail

readonly GENERATED_MARKER="# Generated by scripts/generate-codex-agents.sh; do not edit."
readonly LEGACY_MARKER="# Generated by scripts/generate-codex-agents.py; do not edit."

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
repository_root=$(cd -- "$script_dir/.." && pwd)
source_dir="$repository_root/agents"
output_dir="${CODEX_HOME:-$HOME/.codex}/agents"
dry_run=false
prune=true

usage() {
    cat <<EOF
Usage: $(basename "$0") [options]

Generate Codex custom-agent TOML files from Markdown definitions.

Options:
  --source-dir DIR  Markdown agent directory (default: $source_dir)
  --output-dir DIR  Codex agent directory (default: $output_dir)
  --dry-run         Show changes without writing or removing files
  --no-prune        Keep stale files previously generated by this script
  -h, --help        Show this help
EOF
}

trim() {
    local value=$1
    value="${value#"${value%%[![:space:]]*}"}"
    value="${value%"${value##*[![:space:]]}"}"
    printf '%s' "$value"
}

parse_scalar() {
    local value
    value=$(trim "$1")

    if [[ $value == \"*\" && ${#value} -ge 2 ]]; then
        value=${value:1:${#value}-2}
        value=${value//\\\"/\"}
        value=${value//\\\\/\\}
    elif [[ $value == \'*\' && ${#value} -ge 2 ]]; then
        value=${value:1:${#value}-2}
        value=${value//\'\'/\'}
    fi

    printf '%s' "$value"
}

toml_string() {
    local value=$1
    value=${value//\\/\\\\}
    value=${value//\"/\\\"}
    value=${value//$'\t'/\\t}
    value=${value//$'\r'/\\r}
    value=${value//$'\n'/\\n}
    printf '"%s"' "$value"
}

while (($# > 0)); do
    case "$1" in
        --source-dir)
            (($# >= 2)) || { echo "Missing value for --source-dir" >&2; exit 2; }
            source_dir=$2
            shift 2
            ;;
        --output-dir)
            (($# >= 2)) || { echo "Missing value for --output-dir" >&2; exit 2; }
            output_dir=$2
            shift 2
            ;;
        --dry-run)
            dry_run=true
            shift
            ;;
        --no-prune)
            prune=false
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "Unknown option: $1" >&2
            usage >&2
            exit 2
            ;;
    esac
done

source_dir=${source_dir/#\~/$HOME}
output_dir=${output_dir/#\~/$HOME}

[[ -d $source_dir ]] || { echo "Source directory does not exist: $source_dir" >&2; exit 1; }

shopt -s nullglob
sources=("$source_dir"/*.md)
((${#sources[@]} > 0)) || { echo "No Markdown agent definitions found in $source_dir" >&2; exit 1; }

declare -A generated_destinations=()
declare -A source_by_name=()
declare -a destinations=()
declare -a contents=()

for source in "${sources[@]}"; do
    IFS= read -r first_line < "$source" || true
    [[ $first_line == "---" ]] || { echo "$source: expected YAML frontmatter" >&2; exit 1; }

    name=""
    description=""
    model=""
    frontmatter_closed=false
    line_number=1

    while IFS= read -r line; do
        ((line_number += 1))
        if [[ $line == "---" ]]; then
            frontmatter_closed=true
            break
        fi
        [[ -z ${line//[[:space:]]/} || $line == \#* ]] && continue

        key=${line%%:*}
        if [[ $line != *:* || -z $(trim "$key") ]]; then
            echo "$source:$line_number: expected 'key: value'" >&2
            exit 1
        fi
        value=${line#*:}
        case "$(trim "$key")" in
            name) name=$(parse_scalar "$value") ;;
            description) description=$(parse_scalar "$value") ;;
            model) model=$(parse_scalar "$value") ;;
        esac
    done < <(tail -n +2 "$source")

    $frontmatter_closed || { echo "$source: unterminated YAML frontmatter" >&2; exit 1; }
    [[ -n $name ]] || { echo "$source: missing required frontmatter field 'name'" >&2; exit 1; }
    [[ $name =~ ^[A-Za-z0-9_-]+$ ]] || { echo "$source: unsupported agent name '$name'" >&2; exit 1; }
    [[ -n $description ]] || { echo "$source: missing required frontmatter field 'description'" >&2; exit 1; }

    instructions=$(awk '
        /^---[[:space:]]*$/ { separators++; next }
        separators >= 2 {
            if (!started && $0 ~ /^[[:space:]]*$/) next
            started = 1
            print
        }
    ' "$source")
    [[ -n $instructions ]] || { echo "$source: agent instructions are empty" >&2; exit 1; }

    if [[ -n ${source_by_name[$name]+set} ]]; then
        echo "Duplicate agent name '$name': ${source_by_name[$name]} and $source" >&2
        exit 1
    fi
    source_by_name[$name]=$source

    destination="$output_dir/$name.toml"
    generated_destinations[$destination]=1
    destinations+=("$destination")

    content="$GENERATED_MARKER
# Source: agents/$(basename "$source")

name = $(toml_string "$name")
description = $(toml_string "$description")"
    if [[ -n $model && $model != "inherit" ]]; then
        content+=$'\n'"model = $(toml_string "$model")"
    fi
    content+=$'\n'"developer_instructions = $(toml_string "$instructions")"
    contents+=("$content")
done

created=0
updated=0
unchanged=0
removed=0

for index in "${!destinations[@]}"; do
    destination=${destinations[$index]}
    content=${contents[$index]}
    existing=""
    [[ -f $destination ]] && existing=$(<"$destination")

    if [[ -f $destination && $existing == "$content" ]]; then
        ((unchanged += 1))
        continue
    fi

    if [[ -f $destination ]]; then
        echo "$($dry_run && echo 'Would update' || echo 'Updated'): $destination"
        ((updated += 1))
    else
        echo "$($dry_run && echo 'Would create' || echo 'Created'): $destination"
        ((created += 1))
    fi

    if ! $dry_run; then
        mkdir -p -- "$output_dir"
        temporary_file=$(mktemp "$output_dir/.$(basename "$destination").XXXXXX")
        printf '%s\n' "$content" > "$temporary_file"
        mv -- "$temporary_file" "$destination"
    fi
done

if [[ -d $output_dir ]] && $prune; then
    for candidate in "$output_dir"/*.toml; do
        [[ -e $candidate ]] || continue
        [[ -z ${generated_destinations[$candidate]+set} ]] || continue
        IFS= read -r first_line < "$candidate" || continue
        [[ $first_line == "$GENERATED_MARKER" || $first_line == "$LEGACY_MARKER" ]] || continue

        echo "$($dry_run && echo 'Would remove' || echo 'Removed'): $candidate"
        $dry_run || rm -- "$candidate"
        ((removed += 1))
    done
fi

echo "Agents: ${#destinations[@]}; created: $created; updated: $updated; unchanged: $unchanged; removed: $removed"
